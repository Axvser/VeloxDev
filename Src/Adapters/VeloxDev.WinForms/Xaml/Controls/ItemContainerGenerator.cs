namespace VeloxDev.WinForms.Xaml.Controls;

/// <summary>The lifecycle state of an <see cref="ItemContainerGenerator"/>.</summary>
public enum GeneratorStatus
{
    /// <summary>No item list has been attached.</summary>
    NotStarted,

    /// <summary>Containers are being associated with items.</summary>
    GeneratingContainers,

    /// <summary>Every realized item has a container association.</summary>
    ContainersGenerated,
}

/// <summary>
/// Maps the items of an <see cref="ItemsControl"/> to the controls generated for them.
/// </summary>
/// <remarks>
/// <para>
/// The generator does not create controls; it records the association the owning control establishes while it
/// builds its visuals. In virtualized mode entries outside the viewport are present in <see cref="Items"/> with no
/// container, which is why <see cref="ContainerFromIndex"/> may return <see langword="null"/> for a valid index.
/// </para>
/// <para>
/// This type is single-threaded: the owning control updates it on the UI thread while it rebuilds.
/// </para>
/// </remarks>
public sealed class ItemContainerGenerator
{
    private readonly List<object?> _items = [];
    private readonly List<System.Windows.Forms.Control?> _containers = [];

    /// <summary>Raised after the status changes, and after one generation pass completes.</summary>
    public event EventHandler? StatusChanged;

    /// <summary>The current lifecycle state.</summary>
    public GeneratorStatus Status { get; private set; } = GeneratorStatus.NotStarted;

    /// <summary>The items in source order, including items whose container is not realized.</summary>
    public IReadOnlyList<object?> Items => _items;

    /// <summary>The number of item slots; this is the source item count, not the realized container count.</summary>
    public int Count => _items.Count;

    /// <summary>Returns the container for <paramref name="index"/>, or <see langword="null"/> when it is not realized.</summary>
    /// <param name="index">A zero-based index into <see cref="Items"/>.</param>
    public System.Windows.Forms.Control? ContainerFromIndex(int index)
        => index >= 0 && index < _containers.Count ? _containers[index] : null;

    /// <summary>Returns the container for <paramref name="item"/>, or <see langword="null"/> when none is realized.</summary>
    /// <param name="item">An item from <see cref="Items"/>.</param>
    /// <remarks>Reference equality is tried first, then <see cref="object.Equals(object, object)"/>.</remarks>
    public System.Windows.Forms.Control? ContainerFromItem(object? item)
    {
        var index = IndexOfItem(item);
        return index >= 0 ? _containers[index] : null;
    }

    /// <summary>Returns the index of <paramref name="container"/>, or -1 when it is not generated by this generator.</summary>
    /// <param name="container">A generated item container.</param>
    public int IndexFromContainer(System.Windows.Forms.Control container)
    {
        if (container is null)
        {
            return -1;
        }

        for (var index = 0; index < _containers.Count; index++)
        {
            if (ReferenceEquals(_containers[index], container))
            {
                return index;
            }
        }

        return -1;
    }

    /// <summary>Returns the item represented by <paramref name="container"/>, or <see langword="null"/> when it is unknown.</summary>
    /// <param name="container">A generated item container.</param>
    public object? ItemFromContainer(System.Windows.Forms.Control container)
    {
        var index = IndexFromContainer(container);
        return index >= 0 ? _items[index] : null;
    }

    /// <summary>Forgets every item and container association.</summary>
    public void Clear()
    {
        _items.Clear();
        _containers.Clear();
        SetStatus(GeneratorStatus.NotStarted);
    }

    /// <summary>Drops every container association while keeping <see cref="Items"/>.</summary>
    /// <remarks>
    /// Use this when the visuals are disposed but the item list stays valid; the next generation pass binds new
    /// containers to the same indices.
    /// </remarks>
    public void Reset()
    {
        for (var index = 0; index < _containers.Count; index++)
        {
            _containers[index] = null;
        }

        SetStatus(GeneratorStatus.NotStarted);
    }

    // 以下三个方法由 ItemsControl 在重建视觉时调用：一次 SetItems、若干 SetContainer，最后 CompleteGeneration。
    internal void SetItems(IReadOnlyList<object?> items)
    {
        _items.Clear();
        _items.AddRange(items);
        _containers.Clear();
        for (var index = 0; index < items.Count; index++)
        {
            _containers.Add(null);
        }

        Status = GeneratorStatus.GeneratingContainers;
    }

    internal void SetContainer(int index, System.Windows.Forms.Control? container)
    {
        if (index >= 0 && index < _containers.Count)
        {
            _containers[index] = container;
        }
    }

    internal void CompleteGeneration() => SetStatus(GeneratorStatus.ContainersGenerated);

    private void SetStatus(GeneratorStatus status)
    {
        Status = status;
        StatusChanged?.Invoke(this, EventArgs.Empty);
    }

    private int IndexOfItem(object? item)
    {
        for (var index = 0; index < _items.Count; index++)
        {
            if (ReferenceEquals(_items[index], item))
            {
                return index;
            }
        }

        for (var index = 0; index < _items.Count; index++)
        {
            if (Equals(_items[index], item))
            {
                return index;
            }
        }

        return -1;
    }
}
